// Service workeren (lib/service-worker.js), på roten så den kan betjene alle sider. Verdiene den trenger, settes
// foran den: stiprefikset, filene som skal lagres ved installasjon, og en versjon for den statiske cachen.
import crypto from "node:crypto";
import fs from "node:fs";
import { assetUrl } from "../lib/assets.js";
import { CACHE_SCHEMA, MAX_PAGES, MAX_TILES, offlineUrl, referencedAssets, routeFor, staticToKeep } from "../lib/pwa.js";

// Filer alle sider bruker, pluss skriptene for forsiden og stedssidene. Andre skrifter og bilder lagres
// første gang de brukes.
const PRECACHE = [
  "/assets/css/fonts.css", "/assets/css/styles.css", "/assets/leaflet/leaflet.css", "/assets/leaflet/leaflet.js",
  "/assets/leaflet-markercluster/leaflet.markercluster.js", "/assets/js/trusted-types.js", "/assets/js/theme-init.js", "/assets/js/goatcounter.js",
  "/assets/js/common.js", "/assets/js/pwa.js", "/assets/js/wind.js", "/assets/js/home-logic.js", "/assets/js/home.js", "/assets/js/site.js",
  "/assets/js/site-wind.js", "/assets/js/windgram.js", "/assets/js/lightbox.js",
];
// Skriftene hentes fra fonts.css uten versjonsnummer, så de lagres under sin rene URL.
const FONTS = ["/assets/fonts/barlow-latin-400-normal.woff2", "/assets/fonts/barlow-latin-600-normal.woff2", "/assets/fonts/barlow-condensed-latin-700-normal.woff2"];

export default class {
  data() {
    return { permalink: "/sw.js", eleventyExcludeFromCollections: true };
  }

  render() {
    const base = this.url("/");
    const precache = [...PRECACHE.map(assetUrl), ...FONTS].map((u) => base + u.slice(1));
    const body = fs.readFileSync(new URL("../lib/service-worker.js", import.meta.url), "utf8");
    // Versjonen endres når en lagret fil eller selve service workeren endres (URL-ene har innholdshasher), ikke
    // ved hver bygging. Da installerer nettleseren den nye service workeren, som beholder de gamle filene som
    // lagrede sider fortsatt bruker (lib/service-worker.js activate).
    const version = crypto.createHash("sha256").update(JSON.stringify(precache) + body + routeFor + offlineUrl + referencedAssets + staticToKeep).digest("hex").slice(0, 12);
    return [
      "// Generated by src/sw.11ty.js from lib/service-worker.js and lib/pwa.js.",
      `var VERSION = ${JSON.stringify(version)};`,
      `var SCHEMA = ${JSON.stringify(CACHE_SCHEMA)};`,
      `var BASE = ${JSON.stringify(base)};`,
      `var PRECACHE = ${JSON.stringify(precache)};`,
      `var MAX_TILES = ${MAX_TILES};`,
      `var MAX_PAGES = ${MAX_PAGES};`,
      String(routeFor),
      String(offlineUrl),
      String(referencedAssets),
      String(staticToKeep),
      body,
    ].join("\n");
  }
}
