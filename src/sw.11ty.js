// The service worker (lib/service-worker.js), at the root so it can serve every page. The values it needs are put
// in front of it: the path prefix, the files to store at install, and a version for the static cache.
import crypto from "node:crypto";
import fs from "node:fs";
import { assetUrl } from "../lib/assets.js";
import { CACHE_SCHEMA, MAX_PAGES, MAX_TILES, offlineUrl, routeFor } from "../lib/pwa.js";

// Files every page uses, plus the scripts for the front page and the site pages. Other fonts and images are stored
// when they are first used.
const PRECACHE = [
  "/assets/css/fonts.css", "/assets/css/styles.css", "/assets/leaflet/leaflet.css", "/assets/leaflet/leaflet.js",
  "/assets/leaflet-markercluster/leaflet.markercluster.js", "/assets/js/theme-init.js", "/assets/js/goatcounter.js",
  "/assets/js/common.js", "/assets/js/pwa.js", "/assets/js/wind.js", "/assets/js/home.js", "/assets/js/site.js",
  "/assets/js/site-wind.js", "/assets/js/windgram.js", "/assets/js/lightbox.js",
];
// The fonts are requested from fonts.css without a version number, so they are stored under their plain URL.
const FONTS = ["/assets/fonts/barlow-latin-400-normal.woff2", "/assets/fonts/barlow-latin-600-normal.woff2", "/assets/fonts/barlow-condensed-latin-700-normal.woff2"];

export default class {
  data() {
    return { permalink: "/sw.js", eleventyExcludeFromCollections: true };
  }

  render() {
    const base = this.url("/");
    const precache = [...PRECACHE.map(assetUrl), ...FONTS].map((u) => base + u.slice(1));
    const body = fs.readFileSync(new URL("../lib/service-worker.js", import.meta.url), "utf8");
    // The version changes when a stored file or the service worker itself changes (the URLs carry content hashes),
    // not on every build. Then the browser installs the new service worker, and the old static cache is removed.
    const version = crypto.createHash("sha256").update(JSON.stringify(precache) + body + routeFor + offlineUrl).digest("hex").slice(0, 12);
    return [
      "// Generated by src/sw.11ty.js from lib/service-worker.js and lib/pwa.js.",
      `var VERSION = ${JSON.stringify(version)};`,
      `var SCHEMA = ${JSON.stringify(CACHE_SCHEMA)};`,
      `var BASE = ${JSON.stringify(base)};`,
      `var PRECACHE = ${JSON.stringify(precache)};`,
      `var MAX_TILES = ${MAX_TILES};`,
      `var MAX_PAGES = ${MAX_PAGES};`,
      String(routeFor),
      String(offlineUrl),
      body,
    ].join("\n");
  }
}
